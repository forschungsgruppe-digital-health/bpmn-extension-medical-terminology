#!/usr/bin/env node

import { mkdirSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTerminologyPackageRegistry } from '../build-time/package-discovery.js';

const USAGE = `Usage:
  fdh-terminology-discover --out <file> [options]

Options:
  --root <directory>                 Consumer project root (default: current directory)
  --out <file>                       Generated ESM registry (required)
  --package <name>                   Package to include (repeatable)
  --include <package>=<url>          Include one CodeSystem URL (repeatable)
  --exclude <package>=<url>          Exclude one CodeSystem URL (repeatable)
  --exclude-package <name>           Exclude a package during auto-discovery (repeatable)
  --include-transitive-from <name>   Follow dependencies from this package (repeatable)
  --no-auto-discover                 Disable dependency-based discovery
  --help                             Show this help
`;

function requireValue(argv, index, option) {
  const value = argv[index + 1];
  if (!value || value.startsWith('--')) {
    throw new Error(`Missing value for ${option}.\n\n${USAGE}`);
  }

  return value;
}

function addResourceFilter(filters, argument, option) {
  const separatorIndex = argument.indexOf('=');
  if (separatorIndex < 1 || separatorIndex === argument.length - 1) {
    throw new Error(`Expected ${option} in the form <package>=<CodeSystem.url>.`);
  }

  const packageName = argument.slice(0, separatorIndex);
  const systemUri = argument.slice(separatorIndex + 1);
  const filter = filters[packageName] || {};
  const key = option === '--include' ? 'include' : 'exclude';

  filters[packageName] = {
    ...filter,
    [key]: [...(filter[key] || []), systemUri]
  };
}

export function parseArguments(argv) {
  const options = {
    root: process.cwd(),
    out: null,
    packageNames: [],
    packageFilters: {},
    excludePackages: [],
    includeTransitiveFrom: [],
    autoDiscover: true
  };

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];

    if (argument === '--help' || argument === '-h') {
      return { help: true };
    }

    if (argument === '--root') {
      options.root = resolve(requireValue(argv, index, argument));
      index += 1;
      continue;
    }

    if (argument === '--out') {
      options.out = resolve(requireValue(argv, index, argument));
      index += 1;
      continue;
    }

    if (argument === '--package') {
      options.packageNames.push(requireValue(argv, index, argument));
      index += 1;
      continue;
    }

    if (argument === '--include' || argument === '--exclude') {
      addResourceFilter(
        options.packageFilters,
        requireValue(argv, index, argument),
        argument
      );
      index += 1;
      continue;
    }

    if (argument === '--exclude-package') {
      options.excludePackages.push(requireValue(argv, index, argument));
      index += 1;
      continue;
    }

    if (argument === '--include-transitive-from') {
      options.includeTransitiveFrom.push(requireValue(argv, index, argument));
      index += 1;
      continue;
    }

    if (argument === '--no-auto-discover') {
      options.autoDiscover = false;
      continue;
    }

    throw new Error(`Unknown option "${argument}".\n\n${USAGE}`);
  }

  if (!options.out) {
    throw new Error(`The --out option is required.\n\n${USAGE}`);
  }

  const hasExplicitPackages = options.packageNames.length > 0
    || Object.keys(options.packageFilters).length > 0;
  const packages = hasExplicitPackages
    ? Object.fromEntries([
      ...options.packageNames.map(packageName => [packageName, {}]),
      ...Object.entries(options.packageFilters)
    ].map(([packageName, filter]) => [
      packageName,
      {
        ...(filter || {}),
        ...(options.packageFilters[packageName] || {})
      }
    ]))
    : undefined;

  return {
    root: options.root,
    out: options.out,
    packages,
    autoDiscover: options.autoDiscover,
    exclude: options.excludePackages,
    ...(options.includeTransitiveFrom.length > 0
      ? { includeTransitiveFrom: options.includeTransitiveFrom }
      : {})
  };
}

function serialize(value) {
  return JSON.stringify(value, null, 2)
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

export function createRegistryModule(registry) {
  return [
    '// Generated by fdh-terminology-discover. Do not edit.',
    `export const packageMetadata = ${serialize(registry.metadata)};`,
    '',
    `export default ${serialize(registry.packages)};`,
    ''
  ].join('\n');
}

export function generateTerminologyRegistry(options) {
  const registry = loadTerminologyPackageRegistry(options);
  mkdirSync(dirname(options.out), { recursive: true });
  writeFileSync(options.out, createRegistryModule(registry), 'utf-8');

  return {
    packageCount: Object.keys(registry.packages).length,
    codeSystemCount: Object.values(registry.packages)
      .reduce((count, codeSystems) => count + codeSystems.length, 0)
  };
}

export function main(argv = process.argv.slice(2)) {
  const options = parseArguments(argv);
  if (options.help) {
    console.log(USAGE);
    return;
  }

  const result = generateTerminologyRegistry(options);
  console.log(
    `[fdh-terminology] Generated ${result.codeSystemCount} CodeSystem(s) ` +
    `from ${result.packageCount} package(s) in ${options.out}.`
  );
}

function isCliEntryPoint() {
  if (!process.argv[1]) {
    return false;
  }

  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isCliEntryPoint()) {
  try {
    main();
  } catch (error) {
    console.error(`[fdh-terminology] ${error.message}`);
    process.exitCode = 1;
  }
}
